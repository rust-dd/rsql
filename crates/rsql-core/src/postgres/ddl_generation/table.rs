use crate::postgres::metadata_schema::{RelationKind, load_relation};
use crate::{
    error::{Error, query_failed},
    mutation::quote_ident,
};
use tokio_postgres::Client;

pub(super) async fn generate(client: &Client, schema: &str, name: &str) -> Result<String, Error> {
    let relation = load_relation(client, schema, name).await?;
    if relation.kind != RelationKind::Table {
        return Err(Error::QueryFailed(
            "Table DDL currently supports ordinary tables only".into(),
        ));
    }
    let oid = relation.oid;
    let topology = client.query_one(
        "SELECT c.relpersistence::text, c.relispartition OR EXISTS(SELECT 1 FROM pg_catalog.pg_inherits WHERE inhrelid = c.oid)
         FROM pg_catalog.pg_class c WHERE c.oid = $1", &[&oid]
    ).await.map_err(query_failed)?;
    if topology.get::<_, bool>(1) {
        return Err(Error::QueryFailed(
            "Table DDL does not support partition or inheritance children".into(),
        ));
    }
    let persistence = match topology.get::<_, &str>(0) {
        "u" => "UNLOGGED ",
        "t" => "TEMPORARY ",
        _ => "",
    };
    let qualified = format!("{}.{}", quote_ident(schema), quote_ident(name));
    let rows = client.query(
        "SELECT format('%I %s', a.attname, pg_catalog.format_type(a.atttypid, a.atttypmod)) ||
                CASE WHEN a.attcollation <> t.typcollation THEN format(' COLLATE %I.%I', cn.nspname, col.collname) ELSE '' END ||
                CASE a.attidentity WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY' WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY'
                ELSE CASE WHEN a.attgenerated = 's' THEN ' GENERATED ALWAYS AS (' || pg_catalog.pg_get_expr(d.adbin, d.adrelid) || ') STORED'
                ELSE COALESCE(' DEFAULT ' || pg_catalog.pg_get_expr(d.adbin, d.adrelid), '') END END ||
                CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END
         FROM pg_catalog.pg_attribute a
         JOIN pg_catalog.pg_type t ON t.oid = a.atttypid
         LEFT JOIN pg_catalog.pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
         LEFT JOIN pg_catalog.pg_collation col ON col.oid = a.attcollation
         LEFT JOIN pg_catalog.pg_namespace cn ON cn.oid = col.collnamespace
         WHERE a.attrelid = $1 AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum", &[&oid]
    ).await.map_err(query_failed)?;
    let columns: Vec<String> = rows
        .iter()
        .map(|r| format!("  {}", r.get::<_, String>(0)))
        .collect();
    let mut ddl = vec![format!(
        "CREATE {persistence}TABLE {qualified} (\n{}\n);",
        columns.join(",\n")
    )];
    let constraints = client.query(
        "SELECT contype::text, format('ALTER TABLE %I.%I ADD CONSTRAINT %I %s;', $2::text, $3::text, conname, pg_catalog.pg_get_constraintdef(oid, false))
         FROM pg_catalog.pg_constraint WHERE conrelid = $1
         ORDER BY CASE contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 WHEN 'f' THEN 3 ELSE 2 END, conname, oid",
        &[&oid, &schema, &name]
    ).await.map_err(query_failed)?;
    ddl.extend(
        constraints
            .iter()
            .filter(|r| r.get::<_, &str>(0) != "f")
            .map(|r| r.get::<_, String>(1)),
    );
    ddl.extend(indexes(client, oid).await?);
    ddl.extend(
        constraints
            .iter()
            .filter(|r| r.get::<_, &str>(0) == "f")
            .map(|r| r.get::<_, String>(1)),
    );
    let triggers = client
        .query(
            "SELECT pg_catalog.pg_get_triggerdef(oid, false) || ';',
                format('ALTER TABLE %I.%I %s TRIGGER %I;', $2::text, $3::text,
                    CASE tgenabled WHEN 'D' THEN 'DISABLE' WHEN 'R' THEN 'ENABLE REPLICA' WHEN 'A' THEN 'ENABLE ALWAYS' ELSE 'ENABLE' END, tgname)
         FROM pg_catalog.pg_trigger WHERE tgrelid = $1 AND NOT tgisinternal ORDER BY tgname",
            &[&oid, &schema, &name],
        )
        .await
        .map_err(query_failed)?;
    ddl.extend(
        triggers
            .iter()
            .flat_map(|r| [r.get::<_, String>(0), r.get::<_, String>(1)]),
    );
    let rules = client
        .query(
            "SELECT pg_catalog.pg_get_ruledef(oid, false),
                format('ALTER TABLE %I.%I %s RULE %I;', $2::text, $3::text,
                    CASE ev_enabled WHEN 'D' THEN 'DISABLE' WHEN 'R' THEN 'ENABLE REPLICA' WHEN 'A' THEN 'ENABLE ALWAYS' ELSE 'ENABLE' END, rulename)
         FROM pg_catalog.pg_rewrite WHERE ev_class = $1 AND rulename <> '_RETURN' ORDER BY rulename",
            &[&oid, &schema, &name],
        )
        .await
        .map_err(query_failed)?;
    ddl.extend(
        rules
            .iter()
            .flat_map(|r| [r.get::<_, String>(0), r.get::<_, String>(1)]),
    );
    let rls = client
        .query_one(
            "SELECT relrowsecurity, relforcerowsecurity FROM pg_catalog.pg_class WHERE oid = $1",
            &[&oid],
        )
        .await
        .map_err(query_failed)?;
    if rls.get::<_, bool>(0) {
        ddl.push(format!(
            "ALTER TABLE {qualified} ENABLE ROW LEVEL SECURITY;"
        ));
    }
    if rls.get::<_, bool>(1) {
        ddl.push(format!("ALTER TABLE {qualified} FORCE ROW LEVEL SECURITY;"));
    }
    let policies = client.query(
        "SELECT format('CREATE POLICY %I ON %I.%I AS %s FOR %s TO %s', polname, $2::text, $3::text,
           CASE WHEN polpermissive THEN 'PERMISSIVE' ELSE 'RESTRICTIVE' END,
           CASE polcmd WHEN 'r' THEN 'SELECT' WHEN 'a' THEN 'INSERT' WHEN 'w' THEN 'UPDATE' WHEN 'd' THEN 'DELETE' ELSE 'ALL' END,
           (SELECT string_agg(CASE WHEN role_oid = 0 THEN 'PUBLIC' ELSE quote_ident(pg_catalog.pg_get_userbyid(role_oid)) END, ', ' ORDER BY pos)
            FROM unnest(polroles) WITH ORDINALITY r(role_oid, pos))) ||
           COALESCE(' USING (' || pg_catalog.pg_get_expr(polqual, polrelid) || ')', '') ||
           COALESCE(' WITH CHECK (' || pg_catalog.pg_get_expr(polwithcheck, polrelid) || ')', '') || ';'
         FROM pg_catalog.pg_policy WHERE polrelid = $1 ORDER BY polname", &[&oid, &schema, &name]
    ).await.map_err(query_failed)?;
    ddl.extend(policies.iter().map(|r| r.get::<_, String>(0)));
    ddl.extend(comments(client, oid, schema, name, "TABLE").await?);
    Ok(ddl.join("\n\n"))
}

pub(super) async fn indexes(client: &Client, oid: u32) -> Result<Vec<String>, Error> {
    Ok(client
        .query(
            "SELECT pg_catalog.pg_get_indexdef(i.indexrelid) || ';' FROM pg_catalog.pg_index i
         JOIN pg_catalog.pg_class idx ON idx.oid = i.indexrelid WHERE i.indrelid = $1
           AND NOT EXISTS(SELECT 1 FROM pg_catalog.pg_constraint c WHERE c.conrelid = i.indrelid
              AND c.conindid = i.indexrelid AND c.contype IN ('p','u','x')) ORDER BY idx.relname",
            &[&oid],
        )
        .await
        .map_err(query_failed)?
        .iter()
        .map(|r| r.get(0))
        .collect())
}

pub(super) async fn comments(
    client: &Client,
    oid: u32,
    schema: &str,
    name: &str,
    kind: &str,
) -> Result<Vec<String>, Error> {
    Ok(client.query(
        "SELECT CASE WHEN d.objsubid = 0 THEN format('COMMENT ON %s %I.%I IS %L;', $4::text, $2::text, $3::text, d.description)
         ELSE format('COMMENT ON COLUMN %I.%I.%I IS %L;', $2::text, $3::text, a.attname, d.description) END
         FROM pg_catalog.pg_description d
         LEFT JOIN pg_catalog.pg_attribute a ON a.attrelid = d.objoid AND a.attnum = d.objsubid
         WHERE d.classoid = 'pg_catalog.pg_class'::regclass AND d.objoid = $1 ORDER BY d.objsubid",
        &[&oid, &schema, &name, &kind]).await.map_err(query_failed)?.iter().map(|r| r.get(0)).collect())
}
